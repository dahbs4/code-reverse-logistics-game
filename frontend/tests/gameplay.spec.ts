import { test,expect } from '@playwright/test'

test('simple weekly plan changes outlook and completes 52 weeks',async({page})=>{
 test.setTimeout(180000)
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByRole('button',{name:'Scenarios',exact:true}).click()
 await page.getByLabel('Game name').fill('Weekly browser validation')
 await page.getByRole('button',{name:'Start scenario'}).first().click()
 await expect(page.getByRole('heading',{name:'Plan your weekly units'})).toBeVisible()
 await expect(page.getByLabel('Advance interval')).toHaveCount(0)
 await expect(page.getByText('Dispatch loads / day')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Save weekly plan'})).toBeEnabled()
 const initial=await page.getByTestId('projected-year-end').innerText()
 await page.getByLabel('Indianapolis planned units per week').fill('600000')
 await page.getByLabel('East Coast planned units per week').fill('300000')
 await expect(page.getByRole('button',{name:'Advance one week'})).toBeDisabled()
 await expect(page.getByRole('button',{name:'Save weekly plan'})).toBeEnabled()
 await expect(page.getByTestId('projected-year-end')).not.toHaveText(initial)
 await page.getByRole('button',{name:'Save weekly plan'}).click()
 await expect(page.getByText('Weekly plan saved. Advance one week when ready.')).toBeVisible()
 await page.getByRole('button',{name:'Save checkpoint',exact:true}).click()
 await page.getByRole('button',{name:'Advance one week'}).click()
 await expect(page.locator('.sim-clock strong')).toHaveText('Week 2')
 await expect(page.getByRole('heading',{name:'Week 1 actuals'})).toBeVisible()
 await page.getByRole('button',{name:'Restore checkpoint',exact:true}).click()
 await expect(page.locator('.sim-clock strong')).toHaveText('Week 1')
 await page.reload()
 await expect(page.getByLabel('Indianapolis planned units per week')).toHaveValue('600000')
 await page.getByLabel('Indianapolis planned units per week').fill('1000001')
 await expect(page.getByRole('alert')).toContainText('Enter whole units')
 await expect(page.getByRole('button',{name:'Save weekly plan'})).toBeDisabled()
 await page.getByLabel('Indianapolis planned units per week').fill('1000000')
 await page.getByLabel('East Coast planned units per week').fill('450000')
 await expect(page.getByRole('button',{name:'Save weekly plan'})).toBeEnabled()
 await page.getByRole('button',{name:'Save weekly plan'}).click()
 await expect(page.getByText('Weekly plan saved. Advance one week when ready.')).toBeVisible()
 await page.screenshot({path:'/tmp/reverse-weekly-plan.png',fullPage:true})
 for(let week=1;week<=52;week++){
  await page.getByRole('button',{name:'Advance one week'}).click()
  if(week<52)await expect(page.locator('.sim-clock strong')).toHaveText(`Week ${week+1}`)
 }
 await expect(page.locator('.completion')).toBeVisible()
 await expect(page.getByRole('button',{name:'Advance one week'})).toBeDisabled()
 await page.getByRole('button',{name:'Annual outlook',exact:true}).click()
 await expect(page.getByText('52 / 52 WEEKS CLOSED')).toBeVisible()
 await page.getByRole('button',{name:'Results',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Weekly decisions'})).toBeVisible()
 await page.getByRole('button',{name:'Weekly plan',exact:true}).click()
 for(const width of [768,390]){
  await page.setViewportSize({width,height:1000})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 }
 expect(errors).toEqual([])
})
