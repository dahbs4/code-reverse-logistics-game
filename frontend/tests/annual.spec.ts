import { test, expect } from '@playwright/test'

test('instructions and annual forecast update after removal actuals', async ({ page }) => {
 await page.goto('/')
 await page.getByRole('button', { name: 'Instructions', exact: true }).click()
 await expect(page.getByRole('heading', { name: 'Your 52-week operating year' })).toBeVisible()
 await expect(page.getByText('420,000 units due to increased non-conveyable freight')).toBeVisible()
 await page.screenshot({ path: '/tmp/reverse-instructions.png', fullPage: true })
 await page.getByRole('button', { name: 'Scenarios', exact: true }).click()
 await page.getByRole('button', { name: 'Start scenario' }).first().click()
 await page.getByRole('button', { name: 'Forecast & planning', exact: true }).click()
 await expect(page.getByRole('heading', { name: '52-week removal forecast' })).toBeVisible()
 await expect(page.getByText('0 / 52 WEEKS CLOSED')).toBeVisible()
 await page.getByRole('button', { name: 'Save checkpoint', exact: true }).click()
 await page.getByLabel('Advance interval').selectOption('168')
 await page.getByRole('button', { name: 'Advance', exact: true }).click()
 await expect(page.getByText('1 / 52 WEEKS CLOSED')).toBeVisible()
 await page.locator('.annual-forecast summary').click()
 await expect(page.locator('.annual-table tbody tr')).toHaveCount(52)
 await expect(page.locator('.annual-table tbody tr').first()).toContainText('actual')
 await page.screenshot({ path: '/tmp/reverse-annual-forecast.png', fullPage: true })
 await page.getByRole('button', { name: 'Restore checkpoint', exact: true }).click()
 await expect(page.getByText('0 / 52 WEEKS CLOSED')).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
